/**
 * Text emission primitives shared by every generator.
 *
 * Generators never concatenate strings by hand: they push lines into a
 * `CodeWriter`, which owns indentation and trailing-newline policy. That keeps
 * emitted files byte-stable, which the cross-target verifier depends on.
 */

export interface GeneratedFile {
  /** Path relative to the output root, always with forward slashes. */
  path: string;
  contents: string;
  /** `true` when the file must be marked executable on POSIX systems. */
  executable?: boolean;
}

export class CodeWriter {
  private readonly lines: string[] = [];
  private depth = 0;

  constructor(private readonly indentUnit = '  ') {}

  indent(): this {
    this.depth += 1;
    return this;
  }

  dedent(): this {
    this.depth = Math.max(0, this.depth - 1);
    return this;
  }

  /** Writes `body()` one level deeper, then restores the previous level. */
  block(body: () => void): this {
    this.indent();
    body();
    this.dedent();
    return this;
  }

  line(text = ''): this {
    if (text === '') this.lines.push('');
    else for (const part of text.split('\n')) this.lines.push(`${this.indentUnit.repeat(this.depth)}${part}`);
    return this;
  }

  lines_(texts: readonly string[]): this {
    for (const t of texts) this.line(t);
    return this;
  }

  /** Adds a blank line unless the buffer is empty or already ends with one. */
  blank(): this {
    if (this.lines.length > 0 && this.lines[this.lines.length - 1] !== '') this.lines.push('');
    return this;
  }

  /** Emits `items` separated by `separator`, with the separator omitted on the last. */
  joinLines(items: readonly string[], separator: string): this {
    items.forEach((item, i) => this.line(i === items.length - 1 ? item : `${item}${separator}`));
    return this;
  }

  toString(): string {
    const body = this.lines.join('\n').replace(/\s+$/, '');
    return body.length > 0 ? `${body}\n` : '';
  }
}

/** Wraps `text` to `width` columns and prefixes every line with `prefix`. */
export function comment(text: string, prefix = '// ', width = 100): string[] {
  const limit = Math.max(20, width - prefix.length);
  const out: string[] = [];
  for (const paragraph of text.split('\n')) {
    let current = '';
    for (const word of paragraph.split(/\s+/).filter(Boolean)) {
      if (current.length === 0) current = word;
      else if (current.length + 1 + word.length <= limit) current += ` ${word}`;
      else {
        out.push(prefix + current);
        current = word;
      }
    }
    out.push(prefix + current);
  }
  return out;
}

