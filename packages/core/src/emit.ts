export function file(path: string, contents: string, executable = false): GeneratedFile {
  return executable ? { path, contents, executable } : { path, contents };
}

/** Serialises a plain object as YAML. Supports the subset the IaC layer needs. */
export function toYaml(value: unknown, depth = 0): string {
  const pad = '  '.repeat(depth);
  if (value === null || value === undefined) return 'null';
  if (typeof value === 'string') return needsYamlQuotes(value) ? JSON.stringify(value) : value;
  if (typeof value === 'number' || typeof value === 'boolean') return String(value);
  if (Array.isArray(value)) {
    if (value.length === 0) return '[]';
    return value
      .map((item) => {
        const rendered = toYaml(item, depth + 1);
        return isScalar(item) ? `${pad}- ${rendered}` : `${pad}-\n${indentBlock(rendered, depth + 1)}`;
      })
      .join('\n');
  }
  const entries = Object.entries(value as Record<string, unknown>).filter(([, v]) => v !== undefined);
  if (entries.length === 0) return '{}';
  return entries
    .map(([key, v]) => {
      if (isScalar(v)) return `${pad}${key}: ${toYaml(v, depth)}`;
      if (Array.isArray(v) && v.length === 0) return `${pad}${key}: []`;
      return `${pad}${key}:\n${toYaml(v, depth + 1)}`;
    })
    .join('\n');
}

function isScalar(value: unknown): boolean {
  return value === null || typeof value === 'string' || typeof value === 'number' || typeof value === 'boolean';
}

function indentBlock(text: string, depth: number): string {
  const pad = '  '.repeat(depth);
  return text
    .split('\n')
    .map((l) => (l.startsWith(pad) ? l : pad + l.trimStart()))
    .join('\n');
}

function needsYamlQuotes(value: string): boolean {
  if (value === '') return true;
  if (/^[-?:,[\]{}#&*!|>'"%@`]/.test(value)) return true;
  if (/:\s/.test(value) || /\s#/.test(value)) return true;
  if (/^(true|false|null|yes|no|on|off|~)$/i.test(value)) return true;
  if (/^-?\d+(\.\d+)?$/.test(value)) return true;
  if (/[\n\r\t]/.test(value)) return true;
  return false;
}
